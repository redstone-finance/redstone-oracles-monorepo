import Decimal from "decimal.js";
import _ from "lodash";
import { CreatedEvent, Event } from "../_autogenerated";
import { getCantonFeedId, REDSTONE_DECIMALS } from "./conversions";
import { makeValueUpdateEvent } from "./price-feed-utils";

export type AnyValue =
  | { tag: "AVInt"; value: string }
  | { tag: "AVDecimal"; value: string }
  | { tag: "AVText"; value: string }
  | { tag: "AVTime"; value: string }
  | { tag: "AVBool"; value: boolean }
  | { tag: "AVList"; value: AnyValue[] }
  | { tag: "AVMap"; value: Record<string, AnyValue> };

export interface CapsuleDataPoint {
  publishedAt: string;
  values: Record<string, AnyValue>;
}

interface CapsuleView {
  content: { dataPoint: CapsuleDataPoint };
}

interface CapsOracleStateArgument {
  writeTimestamp: string;
}

export const CAPSULE_INTERFACE = "Caps.Api.CoreV1:Capsule";
export const CAPS_ORACLE_STATE_TEMPLATE = "RedStoneCapsOracleState:RedStoneCapsOracleState";

export function extractCapsuleEvents(events: Event[]) {
  const createdEvents = events.flatMap((event) =>
    "CreatedEvent" in event ? [event.CreatedEvent] : []
  );
  const writeTimestamp = findCapsWriteTimestamp(createdEvents);
  const priceEvents = writeTimestamp
    ? createdEvents.flatMap((created) => extractCapsulePriceEvents(created, writeTimestamp))
    : [];

  return _.keyBy(priceEvents, (priceEvent) => priceEvent.feedId);
}

function findCapsWriteTimestamp(createdEvents: CreatedEvent[]) {
  const createdState = createdEvents.find((created) =>
    created.templateId.endsWith(CAPS_ORACLE_STATE_TEMPLATE)
  );

  return (createdState?.createArgument as CapsOracleStateArgument | undefined)?.writeTimestamp;
}

function extractCapsulePriceEvents(created: CreatedEvent, writeTimestamp: string) {
  const dataPoint = findCapsuleDataPoint(created);

  if (!dataPoint) {
    return [];
  }

  const packageTimestamp = Date.parse(dataPoint.publishedAt).toString();

  return Object.entries(dataPoint.values).flatMap(([feedId, anyValue]) => {
    if (anyValue.tag !== "AVDecimal") {
      return [];
    }

    const value = new Decimal(anyValue.value).toFixed(REDSTONE_DECIMALS);

    return [
      makeValueUpdateEvent(getCantonFeedId(feedId), { value, packageTimestamp, writeTimestamp }),
    ];
  });
}

function findCapsuleDataPoint(created: CreatedEvent) {
  const capsuleView = created.interfaceViews?.find(({ interfaceId }) =>
    interfaceId.endsWith(CAPSULE_INTERFACE)
  )?.viewValue as CapsuleView | undefined;

  return capsuleView?.content.dataPoint;
}
