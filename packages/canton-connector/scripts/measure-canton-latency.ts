/**
 * Measures the end-to-end price-publication latency for a Canton adapter, using the
 * ledger as the single source of truth:
 *
 *   T0  packageTimestamp  - node iteration timestamp
 *   T2  updateStartTimeMs - relayer's start of the update (payload's unsigned metadata)
 *   T3  writeTimestamp    - relayer's clock when the command was built (per attempt, so a
 *                           wrong-contract retry pushes it far past T2)
 *   T4  recordTime        - the commit on Canton
 *
 * There are two ways to read them, because event visibility differs per party:
 *
 *   - the updater party sees the `WritePrices` ExercisedEvent, which carries the payload
 *     (T0), its unsigned metadata (T2) and `currentTime` (T3); together with the
 *     `recordTime` (T4) of the enclosing transaction that gives all four timestamps;
 *   - the viewer party only sees CreatedEvents, but the adapter contract created by the
 *     consuming choice already holds `feedData` with per-feed `packageTimestamp` (T0) and
 *     `writeTimestamp` (T3) - everything except T2.
 *
 * Both paths are used; T2 is reported only for the updates where it is available.
 *
 * Usage:
 *   yarn measure-canton-latency          # endpoint + auth come from .env / RPC_URLS
 *
 * Env:
 *   TARGET_UPDATES  how many updates to collect (default 200)
 *   OFFSET_WINDOW   offset chunk size per request (default 3000; shrinks on node limits)
 *   PARTY_ID        reading party (defaults to the viewer party from canton-defs.json)
 *   INTERACTIVE     true to prompt for an MFA code
 *   OUT_CSV         path to also write one row per update
 */
