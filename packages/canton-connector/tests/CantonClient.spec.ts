import { CantonClient, JsonCantonApi } from "../src";
import {
  GetActiveContractsPageRequest,
  GetUpdatesPageRequest,
  JsCantonError,
  JsGetActiveContractsResponse,
  JsGetUpdatesPageResponse,
  JsTransaction,
} from "../src/_autogenerated";
import { makeCreatedEvent, mockParticipantResponses, SIGNATORY } from "./test-helpers";

const PARTY = "RedStoneOracleViewer::1220ab";
const INTERFACE_ID = "#redstone-interface-v19:IRedStoneAdapter:IRedStoneAdapter";
const CONTRACT_ID = "cid-1";
const SECOND_CONTRACT_ID = "cid-2";
const THIRD_CONTRACT_ID = "cid-3";
const API_URL = "http://localhost:7575";
const SYNCHRONIZER_ID = "global-domain::1220ab";
const LEDGER_END = 1500;
const REQUESTED_OFFSET = 1200;
const FIRST_PAGE_CONTRACT_IDS = [CONTRACT_ID, SECOND_CONTRACT_ID];
const SECOND_PAGE_CONTRACT_IDS = [THIRD_CONTRACT_ID];
const ALL_CONTRACT_IDS = [...FIRST_PAGE_CONTRACT_IDS, ...SECOND_PAGE_CONTRACT_IDS];
const LEDGER_END_URL = "/v2/state/ledger-end";
const ACTIVE_CONTRACTS_PAGE_URL = "/v2/state/active-contracts-page";
const UPDATES_PAGE_URL = "/v2/updates/get-updates-page";
const PAGE_SPAN = 300;
const FIRST_PAGE_BEGIN = 900;
const EMPTY_PAGE_TOKEN = "";
const REPEATED_PAGE_TOKEN = "page-2";
const POST_METHOD = "POST";
const RECORD_TIME = "2026-11-12T12:46:24Z";
const INVALID_PAGE_TOKEN_ERROR = <JsCantonError>{
  code: "INVALID_ACS_PAGE_TOKEN",
  cause: "The page token was prepared with different active_at_offset",
};
const UNSUPPORTED_REQUEST_ERROR = <JsCantonError>{
  code: "INVALID_ARGUMENT",
  cause: "Invalid value for: body",
};

const response = (createdAtOffset: number, archivedAtOffset?: number) => ({
  created: {
    createdEvent: {
      contractId: CONTRACT_ID,
      offset: createdAtOffset,
      createArgument: { adapterId: "RedStoneAdapter-v19-0.4.0" },
      signatories: [SIGNATORY],
      createdEventBlob: "blob",
    },
    synchronizerId: SYNCHRONIZER_ID,
  },
  ...(archivedAtOffset === undefined
    ? {}
    : { archived: { archivedEvent: { offset: archivedAtOffset }, synchronizerId: "x" } }),
});

const makeClient = (result: object) => {
  const api = new JsonCantonApi(API_URL);
  jest.spyOn(api, "performRequestCollected").mockResolvedValue(result);

  return new CantonClient(api);
};

const read = (result: object, atOffset?: number) =>
  makeClient(result).getCreatedContractData(PARTY, INTERFACE_ID, CONTRACT_ID, undefined, atOffset);

describe("CantonClient.getCreatedContractData", () => {
  it("returns the contract when it is active now", async () => {
    await expect(read(response(1000))).resolves.toMatchObject({ contractId: CONTRACT_ID });
  });

  it("returns nothing when the contract is archived and no offset is given", async () => {
    await expect(read(response(1000, 1200))).resolves.toBeUndefined();
  });

  it("returns nothing when the contract did not exist yet at the requested offset", async () => {
    await expect(read(response(1000), 900)).resolves.toBeUndefined();
  });

  it("returns the contract when it was already created at the requested offset", async () => {
    await expect(read(response(1000), 1000)).resolves.toMatchObject({ contractId: CONTRACT_ID });
  });

  it("returns the contract when it was archived only after the requested offset", async () => {
    await expect(read(response(500, 900), 800)).resolves.toMatchObject({
      contractId: CONTRACT_ID,
    });
  });

  it("returns nothing when the contract was already archived at the requested offset", async () => {
    await expect(read(response(500, 900), 900)).resolves.toBeUndefined();
  });

  it("returns nothing when the contract does not match the filter", async () => {
    const client = makeClient(response(1000));

    await expect(
      client.getCreatedContractData(PARTY, INTERFACE_ID, CONTRACT_ID, () => false)
    ).resolves.toBeUndefined();
  });
});

describe("CantonClient.getAllActiveContractsData", () => {
  let sut: CantonClient;

  beforeEach(() => {
    mockParticipantResponses(({ method, url, body }) => {
      if (url === LEDGER_END_URL) {
        return { offset: LEDGER_END };
      }

      if (url !== ACTIVE_CONTRACTS_PAGE_URL || method !== POST_METHOD) {
        return UNSUPPORTED_REQUEST_ERROR;
      }

      const { activeAtOffset, pageToken } = <GetActiveContractsPageRequest>body;
      const snapshotOffset = activeAtOffset ?? LEDGER_END;
      const tokenOfSnapshot = String(activeAtOffset);

      if (!pageToken) {
        return {
          activeContracts: FIRST_PAGE_CONTRACT_IDS.map((contractId) =>
            makeActiveContract(contractId, snapshotOffset)
          ),
          activeAtOffset: snapshotOffset,
          nextPageToken: tokenOfSnapshot,
        };
      }

      if (pageToken !== tokenOfSnapshot) {
        return INVALID_PAGE_TOKEN_ERROR;
      }

      return {
        activeContracts: SECOND_PAGE_CONTRACT_IDS.map((contractId) =>
          makeActiveContract(contractId, snapshotOffset)
        ),
        activeAtOffset: snapshotOffset,
      };
    });
    sut = new CantonClient(new JsonCantonApi(API_URL));
  });

  afterEach(() => {
    jest.restoreAllMocks();
  });

  it("reads the contracts of every page at the ledger end", async () => {
    const contracts = await sut.getAllActiveContractsData(PARTY, INTERFACE_ID);

    expect(describeContracts(contracts)).toEqual(
      ALL_CONTRACT_IDS.map((contractId) => [contractId, LEDGER_END])
    );
  });

  it("reads the contracts of every page at the requested offset", async () => {
    const contracts = await sut.getAllActiveContractsData(
      PARTY,
      INTERFACE_ID,
      undefined,
      REQUESTED_OFFSET
    );

    expect(describeContracts(contracts)).toEqual(
      ALL_CONTRACT_IDS.map((contractId) => [contractId, REQUESTED_OFFSET])
    );
  });

  it("keeps the contracts of every page that match the filter", async () => {
    const contracts = await sut.getAllActiveContractsData(
      PARTY,
      INTERFACE_ID,
      (createArgument) => (<{ contractId: string }>createArgument).contractId === THIRD_CONTRACT_ID
    );

    expect(describeContracts(contracts)).toEqual([[THIRD_CONTRACT_ID, LEDGER_END]]);
  });

  it("ends at an empty page token", async () => {
    mockParticipantResponses(() => makeContractsPage(EMPTY_PAGE_TOKEN));

    const contracts = await sut.getAllActiveContractsData(
      PARTY,
      INTERFACE_ID,
      undefined,
      LEDGER_END
    );

    expect(describeContracts(contracts)).toEqual(
      FIRST_PAGE_CONTRACT_IDS.map((contractId) => [contractId, LEDGER_END])
    );
  });

  it("fails when a page token comes back a second time", async () => {
    mockParticipantResponses(() => makeContractsPage(REPEATED_PAGE_TOKEN));

    await expect(
      sut.getAllActiveContractsData(PARTY, INTERFACE_ID, undefined, LEDGER_END)
    ).rejects.toThrow(`Active contracts page token ${REPEATED_PAGE_TOKEN} came back a second time`);
  });

  function makeContractsPage(nextPageToken: string) {
    return {
      activeContracts: FIRST_PAGE_CONTRACT_IDS.map((contractId) =>
        makeActiveContract(contractId, LEDGER_END)
      ),
      activeAtOffset: LEDGER_END,
      nextPageToken,
    };
  }

  function makeActiveContract(contractId: string, offset: number) {
    return <JsGetActiveContractsResponse>{
      workflowId: "",
      contractEntry: {
        JsActiveContract: {
          createdEvent: makeCreatedEvent({ contractId, offset, createArgument: { contractId } }),
          synchronizerId: SYNCHRONIZER_ID,
          reassignmentCounter: 0,
        },
      },
    };
  }

  function describeContracts(
    contracts: { createdEvent: { contractId: string; offset: number } }[]
  ) {
    return contracts.map(({ createdEvent }) => [createdEvent.contractId, createdEvent.offset]);
  }
});

describe("CantonClient updates by interface", () => {
  let sut: CantonClient;

  beforeEach(() => {
    mockParticipantResponses(({ method, url, body }) => {
      if (url === LEDGER_END_URL) {
        return { offset: LEDGER_END };
      }

      if (url !== UPDATES_PAGE_URL || method !== POST_METHOD) {
        return UNSUPPORTED_REQUEST_ERROR;
      }

      const { beginOffsetExclusive = 0, endOffsetInclusive = LEDGER_END } = <GetUpdatesPageRequest>(
        body
      );
      const highestPageOffset = Math.min(beginOffsetExclusive + PAGE_SPAN, endOffsetInclusive);

      return {
        updates: [
          { update: { OffsetCheckpoint: { value: { offset: beginOffsetExclusive + 1 } } } },
          { update: { Transaction: { value: makeTransaction(highestPageOffset) } } },
        ],
        lowestPageOffsetExclusive: beginOffsetExclusive,
        highestPageOffsetInclusive: highestPageOffset,
      } satisfies JsGetUpdatesPageResponse;
    });
    sut = new CantonClient(new JsonCantonApi(API_URL));
  });

  afterEach(() => {
    jest.restoreAllMocks();
  });

  it("returns the transactions of the requested offsets and the highest offset of the page", async () => {
    const page = await sut.getUpdatesPageByInterface(
      PARTY,
      REQUESTED_OFFSET,
      LEDGER_END,
      INTERFACE_ID
    );

    expect(page).toEqual({
      transactions: [makeTransaction(LEDGER_END)],
      highestOffset: LEDGER_END,
    });
  });

  it("reads the created and archived contracts of every page up to the ledger end", async () => {
    const updates = await sut.getAllUpdatesByInterface(PARTY, INTERFACE_ID, FIRST_PAGE_BEGIN);

    expect(updates).toEqual({
      offset: LEDGER_END,
      createdEvents: [REQUESTED_OFFSET, LEDGER_END].map((offset) =>
        makeCreatedEvent({ contractId: CONTRACT_ID, offset })
      ),
      archivedContractIds: [SECOND_CONTRACT_ID, SECOND_CONTRACT_ID],
    });
  });

  it("fails when a page does not move past the offset it started after", async () => {
    mockParticipantResponses(({ url, body }) =>
      url === LEDGER_END_URL
        ? { offset: LEDGER_END }
        : {
            updates: [],
            highestPageOffsetInclusive: (<GetUpdatesPageRequest>body).beginOffsetExclusive,
          }
    );

    await expect(
      sut.getAllUpdatesByInterface(PARTY, INTERFACE_ID, FIRST_PAGE_BEGIN)
    ).rejects.toThrow(`Updates page after offset ${FIRST_PAGE_BEGIN} ended at ${FIRST_PAGE_BEGIN}`);
  });

  function makeTransaction(offset: number) {
    return <JsTransaction>{
      updateId: `update-${offset}`,
      effectiveAt: RECORD_TIME,
      events: [
        { CreatedEvent: makeCreatedEvent({ contractId: CONTRACT_ID, offset }) },
        { ArchivedEvent: { offset, nodeId: 0, contractId: SECOND_CONTRACT_ID } },
      ],
      offset,
      synchronizerId: SYNCHRONIZER_ID,
      recordTime: RECORD_TIME,
    };
  }
});
