export const spyOnCapsArchiverLedger = (
  client: CantonClient,
  archivedInterface: string,
  archivedContracts: ActiveContract[],
  roundNumber: number
) => {
  jest.spyOn(client, "getActiveTemplateContractsData").mockResolvedValue([
    activeContract(CAPS_ARCHIVER_ID, {
      definition: CAPS_DEFINITION,
      keptRounds: CAPS_KEPT_ROUNDS.toString(),
      keepPeriod: { microseconds: CAPS_KEEP_PERIOD_MICROSECONDS.toString() },
    }),
  ]);
  spyOnInterfaceActiveContracts(client, {
    [`${Defs.capsInterfaceId}:${ROUND_HEAD_INTERFACE}`]: [
      makeCapsContract(CAPS_ROUND_HEAD_ID, roundNumber, 0),
    ],
    [`${Defs.capsInterfaceId}:${archivedInterface}`]: archivedContracts,
  });

  return jest.spyOn(client, "exerciseChoices").mockResolvedValue({
    results: {},
    metadata: { paidTrafficCost: CAPS_ARCHIVE_PAID_TRAFFIC_COST },
  });
};

