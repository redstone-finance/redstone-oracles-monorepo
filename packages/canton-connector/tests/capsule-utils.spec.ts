import { Event } from "../src/_autogenerated";
import { AnyValue, extractCapsuleEvents } from "../src/utils/capsule-utils";
import {
  BASE_TS,
  makeCapsStateCreatedEvent,
  makeCapsuleCreatedEvent,
  makeCapsuleDataPoint,
  makeCreatedEvent,
} from "./test-helpers";

const FEED_ID = "ETH";
const WRITE_TS = String(BASE_TS + 5_000);
const CAPSULE_ETH_VALUE = "2438.8971420000";
const REDSTONE_ETH_VALUE = "2438.89714200";
const CAPSULE_ETH: AnyValue = { tag: "AVDecimal", value: CAPSULE_ETH_VALUE };
const CAPSULE_NOTE: AnyValue = { tag: "AVText", value: CAPSULE_ETH_VALUE };
const STATE_EVENT: Event = { CreatedEvent: makeCapsStateCreatedEvent(WRITE_TS) };
const capsuleEvent = (values: Record<string, AnyValue>): Event => ({
  CreatedEvent: makeCapsuleCreatedEvent(makeCapsuleDataPoint(values)),
});

describe("extractCapsuleEvents", () => {
  it("emits a ValueUpdate with RedStone decimals for each decimal value of the created capsule", () => {
    const result = extractCapsuleEvents([capsuleEvent({ [FEED_ID]: CAPSULE_ETH }), STATE_EVENT]);

    expect(result).toEqual({
      [FEED_ID]: {
        name: "ValueUpdate",
        feedId: FEED_ID,
        args: [REDSTONE_ETH_VALUE, FEED_ID, WRITE_TS],
        updated: true,
        value: Number(REDSTONE_ETH_VALUE),
      },
    });
  });

  it("skips capsule values that are not decimals", () => {
    const result = extractCapsuleEvents([capsuleEvent({ [FEED_ID]: CAPSULE_NOTE }), STATE_EVENT]);

    expect(result).toEqual({});
  });

  it("ignores a capsule created without the CAPS oracle state", () => {
    expect(extractCapsuleEvents([capsuleEvent({ [FEED_ID]: CAPSULE_ETH })])).toEqual({});
  });

  it("ignores a contract without the capsule interface view", () => {
    expect(extractCapsuleEvents([{ CreatedEvent: makeCreatedEvent() }, STATE_EVENT])).toEqual({});
  });
});
